export const translations = Object.fromEntries(
  rows
    .trim()
    .split("\n")
    .map((row) => {
      const [fr, en, de] = row.split("|");
      if (!fr || !en || !de) throw new Error(`Incomplete translation: ${fr}`);
      return [fr, { en, de }];
    }),
);

export function translate(value, locale = "fr") {
  if (typeof value !== "string" || locale === "fr") return value;
  const key = value.replace(/\s+/g, " ").trim();
  const translated = translations[key]?.[locale];
  if (!translated) return value;
  return value.replace(/\S[\s\S]*\S|\S/, translated);
}
